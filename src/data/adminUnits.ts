// Khởi tạo bản đồ tra cứu nhanh với alias fallback cho các ID cũ
export const ADMIN_UNITS_DATA: Record<string, AdminUnit> = (() => {
  const map: Record<string, AdminUnit> = {};

  // 1. Nạp tất cả 168 đơn vị hiện hành (ưu tiên chính thức)
  for (const unit of ADMIN_UNITS) {
    map[unit.id] = unit;
  }

  // 2. Nạp liên kết fallback cho các mã ID lịch sử trỏ tới đơn vị hiện hành
  for (const hist of HISTORICAL_ADMIN_UNITS) {
    if (!map[hist.id]) {
      const target = map[hist.mergedIntoId];
      if (target) {
        // Trỏ alias về đơn vị hiện hành tương ứng để tránh lỗi ứng dụng
        map[hist.id] = {
          ...target,
          subTitle: `${target.subTitle} (Kế thừa từ ${hist.name})`,
        };
      } else {
        map[hist.id] = hist;
      }
    }
  }

  return map;
})();
